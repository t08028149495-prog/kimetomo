/* 売り買い（お金やモノのやりとり）を思わせる書き込みを、送る前に止める。
   投稿・コメント・グループチャット（js/soft-filter.js の kmWarnOk）と個人チャット（dm.html）から使う。
   本当の確認はデータベースで行う（supabase/trade_guard.sql の kimetomo_trade_patterns）。
   ここの一覧を変えたら、SQL の一覧も同じに直すこと。
   文は「ひらがな→カタカナ・全角→半角・小文字・空白や記号（ー も）を取り除く」にそろえてから調べる。
   なので、ここの言葉もカタカナ・ー なしで書く（例：オーケー → オケ、ディーエム → ディエム）。 */
(function(){
 const PAY='(?:paypay|ペイペイ|linepay|ラインペイ|メルペイ|楽天ペイ|aupay|d払イ|kyash|アマギフ|amazonギフト|アマゾンギフト|ギフトカド|ギフト券|itunesカド|googleplayカド|プリペイドカド|ウェブマネ|webmoney|ビットコイン|btc)';
 const ASK='(?:クダサイ|下サイ|クレ|ホシイ|欲シイ|モラエ|モライタイ|イタダケ|クレル|クレマセンカ)';
 const patterns=[
  // 売る
  '(?:売|ウ)リ(?:マス|マセンカ|タイ|マショウカ)',
  '(?:売|ウ)ッテ'+ASK,
  '売ッテル(?:人|方|ヒト|カタ)',
  '販売(?:シマス|中|シテマス|シテイマス|可|シテル)',
  '売ルヨ',
  '売リ手',
  '売買(?:シマス|シマセンカ|シタイ|希望|可|オ願)',
  // 買う
  '(?:買|カ)イ(?:取|ト)リ',
  '買取',
  '買イ(?:マセンカ|手)',
  '買ッテ'+ASK,
  '購入(?:希望|シタイ人|デキル)',
  // 譲る（「譲)」「求)」は交換・売買の書き方）
  '(?:譲|ユズ)(?:リマス|レマス|リタイ|ルヨ|リマショウカ|ッテ'+ASK+')',
  '譲渡',
  'オ譲リ',
  '(?:譲|求)\\)',
  // 取り引き
  '取リ?引キ?(?:シマセンカ|シマショ|シタイ|シテクレ|シテクダサイ|シテ下サイ|シヨ|希望|可|デキマス|デキル|オ願)',
  // お金の受け渡し
  '(?:着|前|先)払イ(?:デ|ナラ|可|ok|オ願|ノミ|限定|ダケ|デキ)',
  '振込先',
  '振リ?込ン?デ(?:クダサイ|下サイ|クレ|ホシイ|モラエ|イタダケ)',
  '送金(?:シテクダサイ|シテ下サイ|シテクレ|シテホシイ|オ願|先)',
  '口座(?:ヲ)?(?:教エテ|番号教)',
  PAY+'(?:デ|ニ|ヲ)?(?:送ッテ|払ッテ|振リ?込ンデ|送金シテ)'+ASK,
  PAY+'(?:デ|ノ)?(?:支払|決済|払イ)?(?:オ願|可|ok|デ大丈夫|デイイ|モ可|ノミ|限定)',
  // モノの受け渡し
  '手渡シ(?:可|ok|デキ|ナラ|希望|ノミ|限定|オ願|デオ願|デ取リ?引|デ売|デ譲)',
  '(?:郵送|発送)(?:シマス|可|デキ|シテクレ|シテクダサイ|シテ下サイ)',
  '匿名配送',
  '即(?:納|日発送)',
  '在庫(?:アリマス|アルヨ|有リマス)',
  // 値段
  '値(?:下ゲ|引キ)(?:可|シマス|ok|デキ)',
  '卸(?:シマス|値|売)',
  '言イ値',
  '\\d+(?:万円?|千円?|円|k)デ(?:売|譲|買|ドウ(?!ニ|シ|ヤ|モ|セ|イウ|カシ)|イカガ|可|ok|取リ?引|手渡|オ願|ユズ|ウリ|ウッ)',
  '(?:g|グラム)(?:単価|イクラ|何円|ナンエン)',
  '\\dパケ(?!ット)',
  'パケ(?:売|イクラ|何円|ナンエン)'
 ].map(p=>new RegExp(p));
 window.kmTradePatterns=patterns.map(r=>r.source); // SQL の一覧と見比べる用
 const en=/(^|[^a-z0-9])(?:wts|wtb|for sale)([^a-z0-9]|$)/;
 const kata=t=>t.replace(/[ぁ-ゖ]/g,c=>String.fromCharCode(c.charCodeAt(0)+0x60));
 const hira=t=>t.replace(/[ァ-ヶ]/g,c=>String.fromCharCode(c.charCodeAt(0)-0x60));
 const norm=t=>kata((t||'').normalize('NFKC').toLowerCase());
 const squeeze=t=>norm(t).replace(/[\s・･.\-_*~〜ー―‐/\\|,、。!！?？☆★♪♡❤]+/g,'');
 window.kmTradeHit=text=>{
  const sq=squeeze(text);
  for(const re of patterns){const m=sq.match(re);if(m)return hira(m[0])}
  const e=norm(text).match(en);
  return e?e[0].replace(/[^a-z ]/g,'').trim():null;
 };
 window.kmTradeMessage=w=>'🚫 売り買いを思わせる言葉（「'+w+'」）が含まれているため、送れません。\n\nキメ友では、メンバー同士の売り買い（お金やモノのやりとり）は禁止です。\n内容を変えてください。';
})();
